CREATE OR ALTER PROCEDURE "PRC_RETURN_BOOK"
(
  "P_BOOK_ID" "D_ID",
  "P_MEMBER_ID" "D_ID"
)
AS
BEGIN
  UPDATE "LOAN"
     SET "RETURNED_AT" = CURRENT_TIMESTAMP,
         "STATUS" = 'RETURNED'
   WHERE "BOOK_ID" = :P_BOOK_ID
     AND "MEMBER_ID" = :P_MEMBER_ID
     AND "RETURNED_AT" IS NULL;

  UPDATE "BOOK"
     SET "STATUS" = 'AVAILABLE'
   WHERE "ID" = :P_BOOK_ID;
END
