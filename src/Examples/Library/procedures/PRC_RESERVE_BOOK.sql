CREATE OR ALTER PROCEDURE "PRC_RESERVE_BOOK"
(
  "P_ID" "D_ID",
  "P_BOOK_ID" "D_ID",
  "P_MEMBER_ID" "D_ID",
  "P_EXPIRES_AT" TIMESTAMP,
  "P_NOTE" "D_NOTE"
)
AS
BEGIN
  INSERT INTO "RESERVATION" ("ID", "BOOK_ID", "MEMBER_ID", "RESERVED_AT", "EXPIRES_AT", "NOTE")
  VALUES (:P_ID, :P_BOOK_ID, :P_MEMBER_ID, CURRENT_TIMESTAMP, :P_EXPIRES_AT, :P_NOTE);
END
