CREATE OR ALTER PROCEDURE "PRC_BORROW_BOOK"
(
  "P_BOOK_ID" "D_ID",
  "P_MEMBER_ID" "D_ID",
  "P_DUE_AT" TIMESTAMP
)
AS
BEGIN
  INSERT INTO "LOAN" ("BOOK_ID", "MEMBER_ID", "LOANED_AT", "DUE_AT", "STATUS")
  VALUES (:P_BOOK_ID, :P_MEMBER_ID, CURRENT_TIMESTAMP, :P_DUE_AT, 'ACTIVE');

  UPDATE "BOOK"
     SET "STATUS" = 'ON_LOAN'
   WHERE "ID" = :P_BOOK_ID;
END
